Реализован серверный агент, который нормализует названия должностей действующих сотрудников, дополняет справочник типовых должностей (position_common) недостающими записями и проставляет каждому сотруднику ссылку на соответствующую типовую должность.

Что сделано:

Из collaborators выбраны все действующие сотрудники (is_dismiss = 0) с непустым position_name — 2309 записей.
Названия должностей нормализованы (Trim + UnifySpaces) и продедуплицированы — получено 315 уникальных названий.
Для каждого уникального названия, отсутствующего в справочнике position_commons, создан новый объект position_common через tools.new_doc_by_name(). Справочник вырос с 10 до 316 записей.
Каждому из 2309 сотрудников проставлена ссылка на его типовую должность.

Как связаны collaborator и position_common:
На объекте collaborator нет штатного поля-связи (foreign_elem) на position_common — заводить его через админку не потребовалось. Вместо этого ID типовой должности пишется в кастомное поле custom_elems.f_position_common_id (строкой). Если в дальнейшем понадобится штатная foreign_elem-связь (например, для отчётов/форм, которые не читают custom_elems) — это отдельная доработка вне рамок этой задачи.

Проверено:

Полный прогон на всех 2309 сотрудниках — без единой ошибки (лог чистый, [WARN]/[ERROR] нет).
Повторный прогон подтвердил идемпотентность — новые типовые должности повторно не создаются.
Точечная проверка: два сотрудника с одинаковой должностью «Менеджер» получили один и тот же f_position_common_id; открыты и сверены вручную документы position_common — названия совпадают с должностями сотрудников.
