Исправление бага: путаница комментариев в отчёте "УЭД. Гибкий отчет для администратора"

Файл: ued_report_generate

Описание проблемы

В выгружаемом Excel-отчёте по процессу "Управление эффективностью деятельности" в столбце "Цель деятельности: Комментарий согласующего руководителя" отображался комментарий сотрудника (самооценка) вместо комментария согласующего руководителя (эксперта). Также столбец "Цель деятельности: Самооценка комментарий" дублировал значение статуса самооценки вместо текста комментария.

Причина
В SQL-запросе для получения комментария согласующего руководителя ошибочно использовалось техническое поле view_coll_exec_comment (служебная копия комментария сотрудника для отображения), вместо реального поля эксперта custom_expert_exec_comment.
В массиве colArray, формирующем колонки отчёта, для столбца "Самооценка комментарий" был по ошибке (вероятно, при копировании соседнего блока) указан field, ссылающийся на статус самооценки (staffrating_task_coll_exec_status), вместо поля с текстом комментария (staffrating_task_coll_exec_comment).
Внесённые изменения

1. Исправлен источник данных для комментария согласующего руководителя (эксперта):
// Было:
[task].[data].value('(task/custom_fields/custom_field[name=''view_coll_exec_comment'']/value)[1]', 'varchar(max)') [staffrating_task_expert_comment]

// Стало:
[task].[data].value('(task/custom_fields/custom_field[name=''custom_expert_exec_comment'']/value)[1]', 'varchar(max)') [staffrating_task_expert_comment]

2. Исправлена привязка поля для столбца "Самооценка комментарий":
// Было:
if (staffrating_task_coll_comment)
    colArray.push({title: "Цель деятельности: Самооценка комментарий", field: "staffrating_task_coll_exec_status"});

// Стало:
if (staffrating_task_coll_comment)
    colArray.push({title: "Цель деятельности: Самооценка комментарий", field: "staffrating_task_coll_exec_comment"});

Результат
Столбец "Комментарий согласующего руководителя" теперь отображает реальный комментарий эксперта, а не дублирует комментарий сотрудника.
Столбец "Самооценка комментарий" отображает текст комментария сотрудника, а не статус.
