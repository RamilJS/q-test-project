Вот коротко:

Общее — все сотрудники, которые входят в аудиторию конкретной программы (по должности + мир-коду хотя бы одного активного элемента этой программы в матрице) и проходят ручные фильтры отчёта (макрорегион, мир-код, должность и т.д.), сгруппированные по городу.

План — равен Общему (период прохождения пока не реализован, это сознательное упрощение).

Факт — из того же пула (аудитория программы + ручные фильтры) берутся те, у кого есть непустая дата прохождения этой программы. Раньше "Факт" считался вообще без проверки аудитории, но по факту тестов оказалось, что так в него попадали люди с совсем других должностей — поэтому сейчас в "Факт" тоже засчитываются только те, кто входит в аудиторию программы.

Обязательно — аудитория программы минус те, кто её уже прошёл (то есть ещё не прошедшие).

Процент — Факт делить на План, округление до целого. Если План = 0, ставится "-". Важный нюанс: в тексте ТЗ было написано "план/факт", но при сверке с реальным присланным примером отчёта (Новосибирск 10/11=91%, Красноярск 9/10=90%, Итог 70/72=97%) совпадает только формула факт/план — так и считаем.

Строка (город, программа) появляется, если для неё есть хотя бы 1 человек в Общем или хотя бы 1 в Факте. Сотрудники без указанного города попадают в отдельную группу "(без города)". Внизу таблицы — итоговая строка "Общий итог", сумма по всем городам и программам.
