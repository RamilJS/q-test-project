Тема: Ошибка формирования отчёта у пользователя с правами администратора (WebTutor/WebSoft HCM)
У сотрудника с ролью администратора (login: VL\Olga.Rukhlyada) не работает функционал формирования отчёта — при попытке сформировать отчёт возникает ошибка:

Running background task is not allowed in this context 
(CallMethod(), x-local://wtv/wtv_view_course_report.xms, line 206)

У других пользователей-администраторов (с аналогичным набором прав: access_role=admin, is_arm_admin=1) этот же функционал формирования отчёта работает корректно, ошибка не возникает.

Что уже проверено и исключено:

Права доступа (роли, флаги is_arm_admin/is_content_admin/is_application_admin, category_id) — соответствуют рабочим учётным записям, различий не выявлено;
Синхронизация данных карточки сотрудника (login, персональные данные) между основным блоком и last_data — приведена в соответствие, на ошибку не повлияло;
Ошибка воспроизводится стабильно именно у данного пользователя, у остальных администраторов с аналогичной конфигурацией прав — нет.

Вопрос к поддержке:
Просим пояснить, при каких условиях в модуле формирования отчётов (wtv_view_course_report.xms, строка 206) возникает ограничение на запуск фоновой задачи (background task) в текущем контексте, и что может влиять на это ограничение для конкретного пользователя (настройки сессии, параметры учётной записи, зависшие фоновые задачи и т.п.). При необходимости готовы предоставить дополнительные логи/данные учётной записи.
